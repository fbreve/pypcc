BASE="b4c100bd22eeff1979a1a581bc73682b8c3705b8"
DATASETS=("iris","wine","breast_cancer","digits")
SEEDS=(76013,76117)
MODES=(True,False)
BATCH_REPS=6
BATCH_FITS=8
PEAK_REPS=2
PROTECTED=("pcc.py","pcc_numba.py","pcc_numpy.py","pcc_graph.py",
           "pcc_step.pyx","pcc_validation.py","setup.py","benchmarks")
RNG_K=(1,2,3,10,17,64,255,1000,2147483649)
STATE_FIELDS=("state_hashes","rng_next","mapped_labels_hash",
              "effective_iterations","stop_reason","checks",
              "stalled_checks","stop_max")


def check(cond,why):
    if not cond:raise AssertionError(why)


def unique(s,old,new):
    check(s.count(old)==1,
          "frozen Numba source anchor no longer unique: "+repr(old[:90]))
    return s.replace(old,new,1)


def canonical():
    subprocess.run(["git","cat-file","-e",BASE+"^{commit}"],
                   check=True,stdout=subprocess.DEVNULL)
    changed=subprocess.check_output([
        "git","diff","--name-only",BASE,"HEAD","--",*PROTECTED],
        text=True).strip()
    check(not changed,"science modified protected production "+changed)
    original=subprocess.check_output(
        ["git","show",BASE+":pcc_numba.py"]).decode("utf-8").replace("\r\n","\n")
    disk=Path("pcc_numba.py").read_text(encoding="utf-8").replace("\r\n","\n")
    check(disk==original,"native Numba production file different from frozen master")
    start="@njit(cache=True)\ndef _pcc_step_numba_sequential("
    finish="@njit(cache=True)\ndef _pcc_calc_mmpot_sequential("
    check(original.count(start)==original.count(finish)==1,
          "frozen true original Numba cached kernel boundaries changed")
    step=original[original.index(start):original.index(finish)]
    updated=unique(
        step,"rand_val = np.random.uniform(0.0, total)",
        "rand_val = np.random.random() * total")
    check(updated.count("np.random.randint(k)")==2 and
          updated.count("np.random.random() < p_grd")==1 and
          updated.count("np.random.random() * total")==1 and
          "np.random.uniform(0.0, total)" not in updated,
          "candidate changed random greedy policy or integer RNG")
    candidate=unique(original,step,updated)
    check(candidate.replace(updated,step,1)==original,
          "candidate unexpectedly changed more than one source expression")
    check(candidate!=original and
          candidate.count("@njit(cache=True)")==4 and
          candidate.count("np.random.randint(k)")==2,
          "candidate not exactly four original compiled native functions")
    return original,candidate


def load_module(path,name):
    spec=importlib.util.spec_from_file_location(name,str(path.resolve()))
    check(spec is not None and spec.loader is not None,
          "not an actual filesystem-backed original Numba file")
    mod=importlib.util.module_from_spec(spec)
    sys.modules[name]=mod
    spec.loader.exec_module(mod)
    check(mod.pcc_propagate_numba.__name__=="pcc_propagate_numba",
          "not exact original Numba native propagator")
    return mod


@njit
def rng_peek():
    return np.random.random()


@njit
def rng_reference_batch(k,steps):
    out=np.empty((steps,4),dtype=np.float64)
    for i in range(steps):
        out[i,0]=np.random.random()
        out[i,1]=np.random.uniform(0.0,3.7)
        out[i,2]=np.random.randint(k)
        out[i,3]=np.random.random()
    return out


@njit
def rng_candidate_batch(k,steps):
    out=np.empty((steps,4),dtype=np.float64)
    for i in range(steps):
        out[i,0]=np.random.random()
        out[i,1]=np.random.random()*3.7
        out[i,2]=np.random.randint(k)
        out[i,3]=np.random.random()
    return out


def rng_control(original):
    data=[]
    for k in RNG_K:
        original._seed_numba_rng(93013)
        old=rng_reference_batch(k,17)
        old_next=float(rng_peek())
        original._seed_numba_rng(93013)
        new=rng_candidate_batch(k,17)
        new_next=float(rng_peek())
        check(np.array_equal(old,new) and old_next==new_next,
              "private Numba state pointer altered random/uniform/randint "+
              repr(k))
        data.append(dict(k=k,samples_hash=array_hash(old),next_numba_rng=old_next))
    return data


@njit
def uniform_reference_edges(total,count):
    data=np.empty(count,dtype=np.float64)
    for i in range(count):
        data[i]=np.random.uniform(0.0,total)
    return data


@njit
def uniform_candidate_edges(total,count):
    data=np.empty(count,dtype=np.float64)
    for i in range(count):
        data[i]=np.random.random()*total
    return data


def strict_uniform_edges(original):
    """Compare bit patterns, not float equality, including NaNs and signed zero."""
    totals=(0.,0.1,1.,1.23,3.7,100000.,1e-300,1e307,
            float("inf"),float("nan"))
    result=[]
    for idx,total in enumerate(totals):
        original._seed_numba_rng(97137)
        left=uniform_reference_edges(total,61)
        left_next=float(rng_peek())
        original._seed_numba_rng(97137)
        right=uniform_candidate_edges(total,61)
        right_next=float(rng_peek())
        check(np.array_equal(left.view(np.uint64),right.view(np.uint64))
              and left_next==right_next,
              "native public uniform bit64 or MT RNG sequence diverged at "+
              repr((idx,total)))
        result.append(dict(index=idx,total_repr=repr(total),
                           stream_bit_sha=array_hash(left.view(np.uint64)),
                           next_numba_rng=left_next))
    return result


def fresh_model(arrays,func):
    model=PCC(impl="numba",update_mode="sequential")
    model.set_graph(arrays["neighbors"],arrays["degrees"],k_nn=10)
    metrics={}
    def wrapper(*args,**kwargs):
        kwargs["return_info"]=True
        output=func(*args,**kwargs)
        metrics.clear()
        metrics.update(output)
        return None
    # Numba >=8 class dominance uses real production C-order branch.
    wrapper.__name__="pcc_propagate_numba"
    model._get_backend_fn=lambda:wrapper
    return model,metrics


def fit_args(cap,mode,seed,pgrd):
    return dict(max_iter=cap,early_stop=mode,seed=seed,
                p_grd=pgrd,delta_v=.1,deltap=1.,dexp=2.,es_chk=2000)


def state(model,pred,metric,cap,mode,seed,read_rng=True):
    if cap==0:
        check(metric["effective_iterations"]==0,
              "zero-iteration original Numba stop contract changed")
    else:
        check(0<metric["effective_iterations"]<=cap,
              "real original Numba effective iterations invalid")
    check(metric["stop_reason"] in ("max_iter","early_stop"),
          "real original stop reason unknown")
    if not mode:
        check(metric["effective_iterations"]==cap,
              "fixed complete native iterations truncated")
    expected_c=model.c>=8
    check(model.node.dominance.flags.c_contiguous if expected_c
          else model.node.dominance.flags.f_contiguous,
          "not true Numba C/F dominance memory layout")
    states={
        "predictions":array_hash(pred),
        "dominance":array_hash(model.node.dominance),
        "positions":array_hash(model.part.curnode),
        "strengths":array_hash(model.part.strength),
        "distances":array_hash(model.part.dist_table),
        "owndeg":array_hash(model.owndeg),
    }
    return dict(state_hashes=states,
                rng_next=float(rng_peek()) if read_rng else None,
                mapped_labels_hash=array_hash(model.mapped_labels),
                effective_iterations=metric["effective_iterations"],
                stop_reason=metric["stop_reason"],
                checks=metric["checks"],stalled_checks=metric["stalled_checks"],
                stop_max=metric["stop_max"],
                cap=cap,mode="monitored" if mode else "fixed",
                native_dominance_layout="C" if expected_c else "F")


def one_fit(arrays,func,mode,cap=30000,seed=0,
            pgrd=.5,track_memory=False):
    model,metric=fresh_model(arrays,func)
    if track_memory:tracemalloc.start()
    try:
        start_cpu=time.process_time_ns()
        start_wall=time.perf_counter_ns()
        pred=model.fit_predict(arrays["labels"],**fit_args(cap,mode,seed,pgrd))
        wall=time.perf_counter_ns()-start_wall
        cpu=time.process_time_ns()-start_cpu
        peak=tracemalloc.get_traced_memory()[1] if track_memory else None
    finally:
        if track_memory:tracemalloc.stop()
    result=state(model,pred,metric,cap,mode,seed)
    result.update(cpu_ns=cpu,wall_ns=wall,peak_bytes=peak)
    return result


def batched_cpu(arrays,func,mode):
    models=[fresh_model(arrays,func) for _ in range(BATCH_FITS)]
    predictions=[None]*BATCH_FITS
    start_cpu=time.process_time_ns()
    start_wall=time.perf_counter_ns()
    for i,(model,metric) in enumerate(models):
        predictions[i]=model.fit_predict(
            arrays["labels"],**fit_args(30000,mode,0,.5))
    wall=time.perf_counter_ns()-start_wall
    cpu=time.process_time_ns()-start_cpu
    check(cpu>0 and wall>0,"original true 8-fit CPU/wall batch not measured")
    # The original Numba MT state contains the FINAL eighth seeded fit.
    # Probe it ONCE after the clock; probing after earlier results would
    # change RNG state and would corrupt the next-native-sample criterion.
    observed=[]
    for i,((model,metric),pred) in enumerate(zip(models,predictions)):
        observed.append(state(model,pred,metric,30000,mode,0,
                              read_rng=(i==BATCH_FITS-1)))
    invariant=("state_hashes","mapped_labels_hash",
               "effective_iterations","stop_reason","checks",
               "stalled_checks","stop_max","native_dominance_layout")
    same=all(all(row[key]==observed[0][key] for key in invariant)
             for row in observed)
    return dict(total_cpu_ns=cpu,total_wall_ns=wall,
                mean_fit_cpu_ns=cpu/BATCH_FITS,
                mean_fit_wall_ns=wall/BATCH_FITS,
                sample_count=BATCH_FITS,
                final=observed[-1],
                all_same=same,
                each_fit_full_state_hashes=[o["state_hashes"] for o in observed])


def identical(x,y,context):
    for field in STATE_FIELDS:
        check(x[field]==y[field],
              "exact original-vs-candidate real Numba RNG/state/stop changed "
              +repr((context,field)))


def case_trials(case,arrays,original,candidate):
    funcs={"original":original.pcc_propagate_numba,
           "candidate":candidate.pcc_propagate_numba}
    warmups=[]
    for mode in MODES:
        for variant,fn in funcs.items():
            result=one_fit(arrays,fn,mode,cap=2)
            check(result["effective_iterations"]==2,
                  "native JIT real 2-step warmup incomplete")
            warmups.append(dict(variant=variant,**result))
    samples=[]
    traced=[]
    for mode in MODES:
        for rep in range(BATCH_REPS):
            order=(("candidate","original") if rep%2==0
                   else ("original","candidate"))
            pair={}
            for variant in order:
                pair[variant]=batched_cpu(arrays,funcs[variant],mode)
                check(pair[variant]["all_same"],
                      "one of 8 native original seeded fits changed state")
            identical(pair["original"]["final"],pair["candidate"]["final"],
                      (case.case_id,mode,rep))
            samples.append(dict(mode="monitored" if mode else "fixed",
                                rep=rep,order=list(order),**pair))
        for rep in range(PEAK_REPS):
            order=(("candidate","original") if rep%2==0
                   else ("original","candidate"))
            trace={}
            for variant in order:
                trace[variant]=one_fit(arrays,funcs[variant],mode,
                                       track_memory=True)
            identical(trace["original"],trace["candidate"],
                      (case.case_id,mode,"memory",rep))
            traced.append(dict(mode="monitored" if mode else "fixed",
                               rep=rep,**trace))
    edges=[]
    for mode in MODES:
        for cap in (2,1001):
            for pgrd in (0.,1.):
                results={
                    v:one_fit(arrays,fn,mode,cap=cap,pgrd=pgrd)
                    for v,fn in funcs.items()}
                identical(results["original"],results["candidate"],
                          (case.case_id,"greedy-boundary",mode,cap,pgrd))
                edges.append(dict(mode="monitored" if mode else "fixed",
                                  cap=cap,p_grd=pgrd,**results))
    no_seed=[]
    for cap in (0,5):
        attempts={}
        for variant,fn in funcs.items():
            original._seed_numba_rng(94013)
            attempts[variant]=one_fit(arrays,fn,False,cap=cap,seed=None)
        identical(attempts["original"],attempts["candidate"],
                  (case.case_id,"unseeded",cap))
        no_seed.append(dict(cap=cap,**attempts))
    return dict(dataset=case.name,seed=case.label_seed,
                case_id=case.case_id,
                labels_sha=array_hash(arrays["labels"]),
                graph_sha=[array_hash(arrays[k]) for k in ("neighbors","degrees")],
                samples=samples,peaks=traced,warmups=warmups,
                policy_cases=edges,no_seed=no_seed)


def main():
    root=Path(__file__).resolve().parents[1]
    os.chdir(root)
    threading=("OPENBLAS_NUM_THREADS","OMP_NUM_THREADS",
               "MKL_NUM_THREADS","NUMBA_NUM_THREADS")
    check(all(os.environ.get(x)=="1" for x in threading),
          "real original NumPy/Numba CPU thread count not controlled")
    old,new=canonical()
    with tempfile.TemporaryDirectory(prefix="pypcc_numba_rng_pointer_") as tmp:
        mods={}
        src_hashes={}
        for variant,source in (("original",old),("candidate",new)):
            sub=Path(tmp)/variant
            sub.mkdir()
            pyfile=sub/f"source_{variant}_numba.py"
            pyfile.write_text(source,encoding="utf-8",newline="\n")
            src_hashes[variant]=hashlib.sha256(source.encode()).hexdigest()
            check(hashlib.sha256(pyfile.read_bytes()).hexdigest()==src_hashes[variant],
                  "frozen source Git blob not exactly written to source-backed Numba module")
            mods[variant]=load_module(pyfile,f"experiment_rng_{variant}_numba")
        rng_fixture=rng_control(mods["original"])
        uniform_edges=strict_uniform_edges(mods["original"])
        preparer=FixturePreparer(prepare_fixture)
        cases=[]
        for ds in DATASETS:
            nodes,features,classes,_=REAL_DATASETS[ds]
            for seed in SEEDS:
                case=Case(ds,nodes,features,classes,k_nn=10,
                          labels_per_class=3,data_seed=0,label_seed=seed)
                arrays,meta=preparer.prepare(case)
                check(meta["labeled_nodes"]==3*classes,
                      "not three real class-balanced homes")
                print("START",case.case_id,flush=True)
                result=case_trials(case,arrays,mods["original"],mods["candidate"])
                result.update(fixture_sha=meta["fixture_sha256"],
                              nodes=nodes,classes=classes,
                              input_sha=array_hash(arrays["x"]),
                              graph_reused=meta["preparation"]["reused"])
                cases.append(result)
                for mode in ("monitored","fixed"):
                    pp=[x for x in result["samples"] if x["mode"]==mode]
                    saved=100*(1-statistics.median(
                        x["candidate"]["total_cpu_ns"]/
                        x["original"]["total_cpu_ns"] for x in pp))
                    print("DONE",case.case_id,mode,
                          "paired eight-fit process CPU saved",round(saved,3),
                          flush=True)
    payload=dict(
        schema=1,base=BASE,
        head=subprocess.check_output(["git","rev-parse","HEAD"],text=True).strip(),
        platform=sys.platform,host=platform.platform(),cpu=platform.processor(),
        python=sys.version,NumPy=np.__version__,
        Numba=__import__("numba").__version__,
        source_sha256=src_hashes["original"],
        candidate_sha256=src_hashes["candidate"],
        threading={k:os.environ[k] for k in threading},
        rng_k_cases=rng_fixture,uniform_edge_cases=uniform_edges,
        full_fit_batch_size=BATCH_FITS,cases=cases)
    Path("numba_public_uniform_results.json").write_text(
        json.dumps(payload,indent=2,allow_nan=False)+"\n",encoding="utf-8")
    print("COMPLETE original vs public-uniform native source pairs: 96 full 8-fit "
          "CPU batches, 32 memory pairs, 64 policy pairs, 16 unseeded pairs "
          "and 10 bitwise float64 uniform edge conditions per OS; exact "
          "native six states/RNG/stop PASS",flush=True)


if __name__=="__main__":
    main()
